//go:build !windows

package diagnostics

import "syscall"

// freeBytes is the space available to an unprivileged user under dir.
func freeBytes(dir string) (uint64, bool) {
	var st syscall.Statfs_t
	if err := syscall.Statfs(dir, &st); err != nil {
		return 0, false
	}
	return uint64(st.Bavail) * uint64(st.Bsize), true //nolint:gosec,unconvert // platform field widths differ
}

// fdLimit is the soft open-file limit.
func fdLimit() (uint64, bool) {
	var rl syscall.Rlimit
	if err := syscall.Getrlimit(syscall.RLIMIT_NOFILE, &rl); err != nil {
		return 0, false
	}
	return uint64(rl.Cur), true //nolint:unconvert // platform field widths differ
}
