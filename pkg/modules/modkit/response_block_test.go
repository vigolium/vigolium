package modkit

import (
	"testing"

	"github.com/vigolium/vigolium/pkg/httpmsg"
)

func respFromRaw(raw string) *httpmsg.HttpResponse {
	return httpmsg.NewHttpResponse([]byte(raw))
}

func TestIsEdgeBlockedResponse(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name string
		raw  string
		want bool
	}{
		{
			name: "cloudfront request blocked 403",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: CloudFront\r\nContent-Type: text/html\r\n\r\n<H1>403 ERROR</H1>The request could not be satisfied.\nGenerated by cloudfront (CloudFront)",
			want: true,
		},
		{
			name: "cloudflare 1020 block page",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: cloudflare\r\nContent-Type: text/html\r\n\r\n<title>Attention Required! | Cloudflare</title><div id=\"cf-error-details\">Sorry, you have been blocked</div>",
			want: true,
		},
		{
			name: "cloudflare plain-text edge error",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: cloudflare\r\nContent-Type: text/plain\r\n\r\nerror code: 1020",
			want: true,
		},
		{
			// The regression: Cloudflare names itself on every proxied response,
			// so an application's own authz 403 behind it is the application.
			name: "app authz 403 behind cloudflare is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: cloudflare\r\nCf-Ray: 8a1b2c3d4e5f-AMS\r\nContent-Type: application/json\r\n\r\n{\"error\":\"forbidden\",\"message\":\"you do not own this order\"}",
			want: false,
		},
		{
			name: "app 503 behind cloudflare is not an edge block",
			raw:  "HTTP/1.1 503 Service Unavailable\r\nServer: cloudflare\r\nContent-Type: application/json\r\n\r\n{\"error\":\"maintenance\"}",
			want: false,
		},
		{
			name: "app authz 403 behind akamai is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: AkamaiGHost\r\nContent-Type: application/json\r\n\r\n{\"error\":\"insufficient_scope\"}",
			want: false,
		},
		{
			name: "app authz 403 behind cloudfront is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: CloudFront\r\nX-Cache: Error from cloudfront\r\nContent-Type: application/json\r\n\r\n{\"message\":\"User is not authorized\"}",
			want: false,
		},
		{
			name: "app authz 403 behind an ELB is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: awselb/2.0\r\nContent-Type: application/json\r\n\r\n{\"error\":\"forbidden\"}",
			want: false,
		},
		{
			name: "ELB/WAF default 403 template",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: awselb/2.0\r\nContent-Type: text/html\r\n\r\n<html>\r\n<head><title>403 Forbidden</title></head>\r\n<body>\r\n<center><h1>403 Forbidden</h1></center>\r\n</body>\r\n</html>",
			want: true,
		},
		{
			name: "incapsula 403 needs its incident page",
			raw:  "HTTP/1.1 403 Forbidden\r\nX-CDN: Incapsula\r\nContent-Type: application/json\r\n\r\n{\"error\":\"forbidden\"}",
			want: false,
		},
		{
			name: "cloudflare challenge 200 by cf-mitigated",
			raw:  "HTTP/1.1 200 OK\r\nServer: cloudflare\r\nCf-Mitigated: challenge\r\n\r\n<html></html>",
			want: true,
		},
		{
			name: "cloudflare js challenge by body marker",
			raw:  "HTTP/1.1 200 OK\r\nContent-Type: text/html\r\n\r\n<html><head></head><body>window._cf_chl_opt={}</body></html>",
			want: true,
		},
		{
			// The motivating case: the Netlify bot-challenge interstitial embeds a
			// proof-of-work JWT whose IP-valued `sub` read as a leaked credential.
			name: "netlify proof-of-work challenge 403",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: Netlify\r\nContent-Type: text/html; charset=utf-8\r\n\r\n<html><body><script>return fetch(\"\\/.netlify\\/submit-challenge\", {method:\"POST\"})</script></body></html>",
			want: true,
		},
		{
			name: "netlify challenge marker unescaped",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: Netlify\r\nContent-Type: text/html\r\n\r\n<form action=\"/.netlify/submit-challenge\"></form>",
			want: true,
		},
		{
			name: "coding-challenge app route is not an edge block",
			raw:  "HTTP/1.1 200 OK\r\nServer: Netlify\r\nContent-Type: text/html\r\n\r\n<form action=\"/api/submit-challenge\">solve the puzzle</form>",
			want: false,
		},
		{
			name: "genuine app 403 on netlify is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: Netlify\r\nContent-Type: application/json\r\n\r\n{\"error\":\"forbidden\"}",
			want: false,
		},
		{
			name: "akamai access denied page",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: AkamaiGHost\r\n\r\n<HTML><HEAD><TITLE>Access Denied</TITLE></HEAD><BODY><H1>Access Denied</H1>Reference&#32;&#35;18&#46;2f1c1702&#46;1700000000&#46;1a2b3c<P>https&#58;&#47;&#47;errors&#46;edgesuite&#46;net</BODY></HTML>",
			want: true,
		},
		{
			// An origin-failure page is the edge reporting an unreachable
			// origin, not a block: no signature row applies on a 502.
			name: "cloudfront 502 origin-failure page is not an edge block",
			raw:  "HTTP/1.1 502 Bad Gateway\r\nServer: CloudFront\r\nContent-Type: text/html\r\n\r\n<H1>502 ERROR</H1>The request could not be satisfied.",
			want: false,
		},
		{
			// Imperva's sensor script rides its ordinary pages: never a
			// challenge, and a block only beside Imperva's header.
			name: "incapsula resource on a 200 is not an edge block",
			raw:  "HTTP/1.1 200 OK\r\nX-Iinfo: 1-2-3\r\nContent-Type: text/html\r\n\r\n<script src=\"/_Incapsula_Resource?SWJIYLWA=719d\"></script>",
			want: false,
		},
		{
			name: "cf-mitigated with another value is not a challenge",
			raw:  "HTTP/1.1 200 OK\r\nCf-Mitigated: block\r\n\r\n<html></html>",
			want: false,
		},
		{
			// Vendor block-page markers count only beside the vendor's header:
			// without it, "The request could not be satisfied" is app text.
			name: "cloudfront marker without a cloudfront header is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: nginx\r\n\r\nThe request could not be satisfied.",
			want: false,
		},
		{
			name: "akamai Reference # on a 200 order page is not an edge block",
			raw:  "HTTP/1.1 200 OK\r\nServer: AkamaiGHost\r\n\r\nOrder Reference #18.2f1c confirmed",
			want: false,
		},
		{
			name: "rate limited 429",
			raw:  "HTTP/1.1 429 Too Many Requests\r\nServer: nginx\r\n\r\nslow down",
			want: true,
		},
		{
			name: "genuine app 403 (nginx) is not an edge block",
			raw:  "HTTP/1.1 403 Forbidden\r\nServer: nginx\r\nContent-Type: application/json\r\n\r\n{\"error\":\"insufficient_scope\"}",
			want: false,
		},
		{
			name: "genuine app 401 is not an edge block",
			raw:  "HTTP/1.1 401 Unauthorized\r\nServer: nginx\r\n\r\n{\"error\":\"unauthorized\"}",
			want: false,
		},
		{
			name: "normal 200 app response",
			raw:  "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n\r\n{\"ok\":true}",
			want: false,
		},
	}
	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if got := IsEdgeBlockedResponse(respFromRaw(tc.raw)); got != tc.want {
				t.Fatalf("IsEdgeBlockedResponse() = %v, want %v", got, tc.want)
			}
		})
	}
}

func TestIsEdgeBlockedResponse_Nil(t *testing.T) {
	t.Parallel()
	if IsEdgeBlockedResponse(nil) {
		t.Fatal("nil response must not be treated as blocked")
	}
}

func TestIsPlaceholderValue(t *testing.T) {
	t.Parallel()
	placeholders := []string{"", "  ", "null", "NULL", "undefined", "nil", "none", "NaN", "(null)", "[object Object]", "{}", "[]"}
	for _, v := range placeholders {
		if !IsPlaceholderValue(v) {
			t.Errorf("IsPlaceholderValue(%q) = false, want true", v)
		}
	}
	real := []string{"abc123", "0", "true", "false", "eyJhbGci.payload.sig", "https://example.com", "42"}
	for _, v := range real {
		if IsPlaceholderValue(v) {
			t.Errorf("IsPlaceholderValue(%q) = true, want false", v)
		}
	}
}
